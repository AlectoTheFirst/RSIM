//! The coverage of the configuration sections of a UniFi site: the networks,
//! the WLANs and the port profiles.
//!
//! Each field of an item has a state. A feature flag that is off, empty or
//! null is known-irrelevant. The same flag when it is on is unhandled,
//! because it can change the forwarding.

use crate::coverage::{Coverage, State};
use crate::stanza::{Body, Document, Stanza};

/// The rules of one section.
pub struct Rules {
    pub handled: &'static [&'static str],
    /// Fields with a forwarding effect when they are on.
    pub flags: &'static [&'static str],
    /// Fields and field prefixes, ending with `*`, with no effect on the
    /// twin.
    pub irrelevant: &'static [&'static str],
}

