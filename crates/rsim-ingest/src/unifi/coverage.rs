fn glob(pattern: &str, key: &str) -> bool {
    match pattern.split_once('*') {
        None => pattern == key,
        Some((a, b)) => key.len() >= a.len() + b.len() && key.starts_with(a) && key.ends_with(b),
    }
}

fn off(s: &Stanza) -> bool {
    match &s.body {
        Body::Scalar(v) => matches!(v.as_str(), "false" | "null" | "" | "0"),
        Body::Object(c) | Body::Array(c) => c.is_empty(),
    }
}

/// The state of a field of an item.
pub fn state(rules: &Rules, field: &Stanza) -> State {
    let k = field.key.as_str();
    if rules.handled.contains(&k) {
        State::Handled
    } else if rules.flags.contains(&k) {
        if off(field) {
            State::Irrelevant
        } else {
            State::Unhandled
        }
    } else if rules.irrelevant.iter().any(|p| glob(p, k)) {
        State::Irrelevant
    } else {
        State::Unhandled
    }
}

/// Adds the coverage of the items of one section. The `data` key and the
/// lines of the items themselves are not counted.
pub fn classify(doc: &Document, section: &str, rules: &Rules, cov: &mut Coverage) {
    let Some(data) = doc.root.get("data") else {
        return;
    };
    for item in data.children() {
        for f in item.children() {
            let st = state(rules, f);
            *cov.lines.entry(st).or_default() += f.last_line - f.first_line + 1;
            if st == State::Unhandled {
                let e = cov
                    .unhandled
                    .entry(format!("{section}/*/{}", f.key))
                    .or_default();
                e.0 += 1;
                e.1 += f.last_line - f.first_line + 1;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::stanza::read_json;

    #[test]
    fn a_flag_is_irrelevant_when_off_and_unhandled_when_on() {
        let doc = read_json(
            br#"{"data": [
                {"_id": "a", "name": "office", "networkconf_id": "n", "l2_isolation": false,
                 "proxy_arp": false, "wpa_mode": "wpa2", "fancy": 1},
                {"_id": "b", "name": "guest", "networkconf_id": "n", "proxy_arp": true}
            ]}"#,
        )
        .unwrap();
        let mut cov = Coverage::default();
        classify(&doc, "wlans", &WLANS, &mut cov);
        let ranked: Vec<&str> = cov.ranked().iter().map(|r| r.0).collect();
        assert_eq!(ranked, ["wlans/*/fancy", "wlans/*/proxy_arp"]);
        assert_eq!(cov.lines[&State::Irrelevant], 3);
    }
}
